import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const MARKER = "<!-- shelfready -->";

/** The note every coding agent in the repo reads (AGENTS.md, or CLAUDE.md when that's what the repo uses). */
export const AGENTS_NOTE = `${MARKER}
## App Store release (ShelfReady)

The privacy policy, support page, Impressum and App Privacy answers are generated by [ShelfReady](https://shelfready.dev) from \`shelfready.yaml\`.

- Before a release, or after adding an SDK, a permission or a privacy manifest: run \`npx -y shelfready check\` and fix what it reports.
- Edit \`shelfready.yaml\`, never the generated pages; regenerate them with \`npx -y shelfready pages\`.
- What's left before submitting: \`npx -y shelfready checklist --online\`.
`;

export interface AgentsNoteResult {
  file: string;
  action: "created" | "appended" | "present";
}

/** Which file gets the note: AGENTS.md if present, else CLAUDE.md if present, else a new AGENTS.md. */
export function agentsNoteFile(root: string): string {
  const agents = join(root, "AGENTS.md");
  const claude = join(root, "CLAUDE.md");
  return existsSync(agents) || !existsSync(claude) ? agents : claude;
}

/** Add the ShelfReady note once. Idempotent: does nothing if the note is already there. */
export function addAgentsNote(root: string): AgentsNoteResult {
  const file = agentsNoteFile(root);
  if (!existsSync(file)) {
    writeFileSync(file, `# Agent notes\n\n${AGENTS_NOTE}`);
    return { file, action: "created" };
  }
  const text = readFileSync(file, "utf8");
  if (text.includes(MARKER) || text.includes("npx -y shelfready check")) return { file, action: "present" };
  writeFileSync(file, `${text.replace(/\s*$/, "")}\n\n${AGENTS_NOTE}`);
  return { file, action: "appended" };
}
