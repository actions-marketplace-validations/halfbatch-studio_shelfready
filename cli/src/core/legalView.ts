import { impressumLines, needsImpressum, pageURL, type Facts } from "./facts.js";

/** Escape a string for a Swift string literal. */
const swift = (s: string) => JSON.stringify(s);

/**
 * A SwiftUI `LegalView` so the Impressum and links are reachable inside the app,
 * which German law expects for commercial apps (the App Store listing alone isn't enough).
 */
export function legalView(facts: Facts): string {
  const p = facts.publisher;
  const lines = p.trader
    ? impressumLines(facts).map(({ label, value }) => (label ? `${label}: ${value}` : value))
    : [`${p.brand || p.name} ist ein privates, nicht-kommerzielles Projekt.`, p.email];

  const impressumSection = needsImpressum(facts)
    ? `
            Section("Impressum") {
${lines.map((l) => `                Text(${swift(l)})`).join("\n")}
            }
`
    : "";

  return `// Generated by \`shelf pages --swiftui\` from shelfready.yaml. Regenerate instead of editing.
import SwiftUI

struct LegalView: View {
    var body: some View {
        List {${impressumSection}
            Section("Links") {
                Link("Privacy policy", destination: URL(string: ${swift(pageURL(facts, "privacy"))})!)
                Link("Support", destination: URL(string: ${swift(pageURL(facts, "support"))})!)${
                  needsImpressum(facts) ? `\n                Link("Impressum (web)", destination: URL(string: ${swift(pageURL(facts, "impressum"))})!)` : ""
                }
            }
        }
        .navigationTitle(${swift(needsImpressum(facts) ? "Impressum & Privacy" : "Privacy & Support")})
    }
}

#Preview {
    NavigationStack { LegalView() }
}
`;
}
