/**
 * Regenerate knowledge/sdks/*.yaml from each SDK's own privacy manifest.
 *
 *   npm run kb:import -- <folder with clones>
 *
 * The folder holds shallow clones named owner_repo (e.g. getsentry_sentry-cocoa); missing ones are cloned
 * with `git clone --depth 1 --filter=blob:none`. Every entry records the repository, commit and file it came from.
 */
import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { parse as parsePlist } from "plist";
import { parse, stringify } from "yaml";
import { privacyManifest } from "../src/core/scan.js";
import type { KnowledgeEntry } from "../src/core/knowledge.js";

interface Source {
  identity: string;
  name: string;
  vendor: string;
  repo: string;
  include: string;
  aliases?: string[];
  notes?: string;
}

const here = resolve(import.meta.dirname, "..");
const clones = resolve(process.argv[2] ?? join(here, ".kb-clones"));
const sources = parse(readFileSync(join(here, "knowledge/sources.yaml"), "utf8")) as Source[];
const today = new Date().toISOString().slice(0, 10);
const git = (dir: string, ...args: string[]) => execFileSync("git", ["-C", dir, ...args], { encoding: "utf8", maxBuffer: 64 << 20 });
const SKIP = /test|example|demo|sample|benchmark|fixture|\.xcframework\//i;

mkdirSync(clones, { recursive: true });
mkdirSync(join(here, "knowledge/sdks"), { recursive: true });

for (const s of sources) {
  const dir = join(clones, s.repo.replace("/", "_"));
  if (!existsSync(dir)) {
    execFileSync("git", ["clone", "-q", "--depth", "1", "--filter=blob:none", "--no-checkout", `https://github.com/${s.repo}`, dir]);
  }
  const commit = git(dir, "rev-parse", "HEAD").trim();
  const include = new RegExp(s.include);
  const paths = git(dir, "ls-tree", "-r", "--name-only", "HEAD")
    .split("\n")
    .filter((p) => p.endsWith("PrivacyInfo.xcprivacy") && include.test(p) && !SKIP.test(p));
  if (paths.length === 0) {
    console.warn(`! ${s.repo}: no manifest matches ${s.include}`);
    continue;
  }

  const products = new Map<string, KnowledgeEntry["products"][number]>();
  for (const path of paths.sort()) {
    let dict: Record<string, unknown>;
    try {
      dict = parsePlist(git(dir, "show", `HEAD:${path}`)) as Record<string, unknown>;
    } catch {
      console.warn(`! ${s.repo}: skipped unreadable ${path}`);
      continue;
    }
    const m = privacyManifest(dict, path);
    const segments = path.split("/").filter((x) => !/^(Sources?|Resources|iOS_SDK|OneSignalSDK|Library|Swift|Extension|Internal|resources)$/.test(x));
    const product = segments.length > 1 ? segments[0]! : s.name;
    const existing = products.get(product);
    const collects = m.collectedDataTypes.map((c) => ({ type: c.type, linked: c.linked, tracking: c.tracking, purposes: c.purposes }));
    if (existing) {
      for (const c of collects) if (!existing.collects.some((e) => JSON.stringify(e) === JSON.stringify(c))) existing.collects.push(c);
      existing.tracking ||= m.tracking;
      existing.trackingDomains = [...new Set([...existing.trackingDomains, ...m.trackingDomains])];
      existing.sources.push(`https://github.com/${s.repo}/blob/${commit}/${path}`);
    } else {
      products.set(product, {
        name: product,
        sources: [`https://github.com/${s.repo}/blob/${commit}/${path}`],
        tracking: m.tracking,
        trackingDomains: m.trackingDomains,
        collects,
      });
    }
  }

  if (products.size === 0) {
    console.warn(`! ${s.repo}: no readable manifest`);
    continue;
  }
  const entry: KnowledgeEntry = {
    identity: s.identity,
    ...(s.aliases ? { aliases: s.aliases } : {}),
    name: s.name,
    vendor: s.vendor,
    repository: `https://github.com/${s.repo}`,
    commit,
    checked: today,
    basis: "The SDK's own privacy manifest(s) at the commit above.",
    products: [...products.values()],
    ...(s.notes ? { notes: s.notes } : {}),
  };
  const header = `# Generated by \`npm run kb:import\` from ${s.repo}@${commit.slice(0, 7)} on ${today}. Edit knowledge/sources.yaml, not this file.\n`;
  writeFileSync(join(here, `knowledge/sdks/${s.identity}.yaml`), header + stringify(entry, { lineWidth: 120 }));
  const types = new Set([...products.values()].flatMap((p) => p.collects.map((c) => c.type.replace("NSPrivacyCollectedDataType", ""))));
  console.log(`✓ ${s.identity}: ${products.size} product(s), collects ${types.size ? [...types].join(", ") : "nothing"}`);
}
